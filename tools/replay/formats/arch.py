def fill_repo(p, fx, repo, steps, labels):
    aa = auth_header("admin")
    for i, (how, where, files) in enumerate(steps):
        if how == "put":
            for _, body in files:
                st, _, out = request("PUT", f"/{repo}" + where.replace("{repo}", repo), aa,
                                     body)
                if st != 201:
                    raise SystemExit(f"arch upload to {repo}: {st} {out[:200]}")
        else:
            paths = []
            for fn, body in files:
                f = os.path.join(fx, fn)
                with open(f, "wb") as fh:
                    fh.write(body)
                paths.append(f)
            p.cli("upload", repo, *paths)
        if i in labels:
            p.cli("label", repo, labels[i])


def seed(p, fx):
    # Arch: hosted public and private, signed (SEED, the labels after
    # the first and the fourth); one unsigned with its own
    # architectures; one with nothing in it.
    for repo, public in (("archpub", "true"), ("archpriv", "false")):
        p.cli("repo", "create", repo, "-f", "arch", "-s", f"public={public}")
        fill_repo(p, fx, repo, SEED, LABELS)
    p.cli("repo", "create", "archnosign", "-f", "arch", "-s", "public=true", "-s", "sign=false",
          "-s", "architectures=x86_64,armv7h")
    fill_repo(p, fx, "archnosign", NOSIGN, {0: "first"})
    p.cli("repo", "create", "archempty", "-f", "arch", "-s", "public=true")


def etag(data):
    return '"%s"' % hashlib.sha256(data).hexdigest()


def dbs(repo):
    """The databases pacman reads of `repo`, and their signatures."""
    return [f"{repo}.{w}{x}{s}" for w in ("db", "files") for x in ("", ".tar.gz")
            for s in ("", ".sig")]


def tree(repo):
    """What each signed repository is asked: its address and listings
    (sorted, of a pacman repository, of an architecture it has, one it
    has only for packages of any, one only extra has, one not there);
    every database of each architecture of each pacman repository; the
    packages, where they are and where they are not, and their
    signatures; key.asc; the state the format keeps beside the files;
    paths mis-cased, cut, escaped, too deep, not safe; the upload
    address; by-hash; a label's, a version's by number, a label not
    there."""
    d = f"/{repo}/x86_64"
    a = f"/{repo}/aarch64"
    out = ["", "/", "/?sort=size&order=desc", "/?sort=time", "/?sort=name&order=desc",
           f"/{repo}", f"/{repo}/", f"/{repo}/?sort=name&order=desc", "/extra", "/extra/",
           "/nope/", d, d + "/", a + "/", f"/{repo}/any/", f"/{repo}/armv7h/", "/extra/x86_64/",
           "/extra/aarch64/", "/extra/any/"]
    for pr in (repo, "extra"):
        for arch in ("x86_64", "aarch64"):
            out += [f"/{pr}/{arch}/{n}" for n in dbs(pr)]
    out += [f"/{repo}/armv7h/{repo}.db", f"/{repo}/any/{repo}.db", f"/extra/x86_64/{repo}.db",
            f"{d}/extra.db", f"{d}/{repo}.db.tar.xz", f"{d}/{repo}.db.tar.zst",
            f"{d}/{repo}.files.tar.zst"]
    for f in (F10, F11, FT, FT2, F110, F19):
        out += [f"{d}/{f}", f"{d}/{f}.sig"]
    for f in (FT, FL):
        out += [f"{a}/{f}", f"{a}/{f}.sig"]
    out += [f"{a}/{F10}", f"{a}/{FT2}", f"{d}/{FL}", f"/{repo}/any/{FT}", f"/extra/x86_64/{FF}",
            f"/extra/x86_64/{FF}.sig", f"/extra/aarch64/{FF}", f"{d}/{FF}",
            f"{a}/lib-2%3A0.5-1-aarch64.pkg.tar.zst", f"{d}/hello-1.0-1-x86_64.pkg.tar.xz",
            f"{d}/hello-1.0-1-aarch64.pkg.tar.zst", f"{d}/{F10}.sig.sig", f"{d}/{F10}.asc",
            "/key.asc", "/key.pub", f"/{repo}.db", f"{d}/_sigs", f"{a}/_sigs", f"/extra/x86_64/_sigs",
            f"{d}/{repo}.db/", f"{d}/{repo}.db/x", f"{d}/{F10}/", f"/{repo.upper()}/x86_64/{repo}.db",
            f"/{repo}/X86_64/{repo}.db", f"{d}/{repo.upper()}.db", f"{d}/HELLO-1.0-1-x86_64.pkg.tar.zst",
            f"/{repo}//x86_64/{repo}.db", f"/{repo}%2fx86_64%2f{repo}.db",
            f"/%2e%2e/{repo}/x86_64/{repo}.db", f"{d}/%2e%2e/aarch64/{repo}.db", f"{d}/%00",
            f"{d}/%FF", f"{d}/..%5c{repo}.db", f"/{repo}/x86_64/{repo}.d%62", "/upload",
            f"/{repo}/upload", "/by-hash/x", f"{d}/by-hash/SHA256/" + "0" * 64,
            "/@first", "/@first/", f"/@first/{repo}/", f"/@first{d}/", f"/@first{d}/{repo}.db",
            f"/@first{d}/{repo}.db.sig", f"/@first{d}/{repo}.files", f"/@first{d}/{F10}",
            f"/@first{d}/{F10}.sig", f"/@first{d}/{F11}", f"/@first{a}/{repo}.db", "/@first/key.asc",
            "/@first/extra/x86_64/extra.db", "/@second/extra/x86_64/extra.db",
            "/@second/extra/x86_64/extra.files.sig", f"/@second{a}/{repo}.files",
            f"/@second{d}/{F110}", "/@nope/", f"/@nope{d}/{repo}.db", f"/@1{d}/{repo}.db",
            f"/@3{a}/{repo}.db", f"/@v2{d}/{F11}", f"/@9999{d}/{repo}.db", f"/@{d}/{repo}.db",
            f"/%40first{d}/{repo}.db", f"/@first/@first{d}/{repo}.db", f"/{repo}/@first/x86_64/{repo}.db",
            f"/@first/by-hash/x86_64/{repo}.db"]
    return out


