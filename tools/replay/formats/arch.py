def fill_repo(p, fx, repo, steps, labels):
    aa = auth_header("admin")
    for i, (how, where, files) in enumerate(steps):
        if how == "put":
            for _, body in files:
                st, _, out = request("PUT", f"/{repo}" + where.replace("{repo}", repo), aa,
                                     body)
                if st != 201:
                    raise SystemExit(f"arch upload to {repo}: {st} {out[:200]}")
        else:
            paths = []
            for fn, body in files:
                f = os.path.join(fx, fn)
                with open(f, "wb") as fh:
                    fh.write(body)
                paths.append(f)
            p.cli("upload", repo, *paths)
        if i in labels:
            p.cli("label", repo, labels[i])


def seed(p, fx):
    # Arch: hosted public and private, signed (SEED, the labels after
    # the first and the fourth); one unsigned with its own
    # architectures; one with nothing in it.
    for repo, public in (("archpub", "true"), ("archpriv", "false")):
        p.cli("repo", "create", repo, "-f", "arch", "-s", f"public={public}")
        fill_repo(p, fx, repo, SEED, LABELS)
    p.cli("repo", "create", "archnosign", "-f", "arch", "-s", "public=true", "-s", "sign=false",
          "-s", "architectures=x86_64,armv7h")
    fill_repo(p, fx, "archnosign", NOSIGN, {0: "first"})
    p.cli("repo", "create", "archempty", "-f", "arch", "-s", "public=true")


def etag(data):
    return '"%s"' % hashlib.sha256(data).hexdigest()


def dbs(repo):
    """The databases pacman reads of `repo`, and their signatures."""
    return [f"{repo}.{w}{x}{s}" for w in ("db", "files") for x in ("", ".tar.gz")
            for s in ("", ".sig")]


