"""Arch: hosted public and private repositories of pacman packages,
signed (hello 1.0-1, a .pkg.tar.zst put to the repository's upload
address as a client does it, then a label; hello 1.1-1, a .pkg.tar.xz
by the CLI; tool 0.1-1 for any architecture, a .pkg.tar.gz, and lib
2:0.5-1 for aarch64 alone in one upload by the CLI; full 3.0-2 with
every field pacman reads, in a pacman repository of its own, extra,
then a second label; hello 1.10-1 put to the address it is served at;
hello 1.9-1, older by pacman's order though put last, with tool 0.2-1
for x86_64 alone), one unsigned with architectures of its own, and
one with nothing in it. Arch repositories are hosted or mirrors (which
are jobs): no proxy, no stub (and no group here: the group corpus has
those).

The server serves a repository as it serves any tree (serving/mod.rs:
get's tree, put, listings, content types, Cache-Control); the format
makes, for each version, <pacman repository>/<architecture>/ of each
pacman repository it has and each architecture it names (x86_64 and
aarch64 unless the settings say others): every package file there
(those for any architecture in each), its signature, the databases
pacman reads (<repository>.db and .files, links .db.tar.gz and
.files.tar.gz, with their signatures) naming the newest version of
each package, and key.asc at the top.

The seed's versions are all dated before the seed, and a package's
signature is kept from version to version while the package and the
key stay: nothing read before the writes holds a time of the run."""

