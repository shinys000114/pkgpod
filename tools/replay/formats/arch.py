# The times inside packages (their files', .PKGINFO's builddate).
TIME = 1790000000


def zst(data, step=128 << 10):
    """`data` as a zstd frame of raw blocks (the standard library writes
    no zstd): a single segment of its size, blocks of `step` bytes (at
    most 128 KiB), no checksum."""
    out = [struct.pack("<IB", 0xFD2FB528, 0xE0), struct.pack("<Q", len(data))]
    pieces = [data[i:i + step] for i in range(0, len(data), step)] or [b""]
    for i, piece in enumerate(pieces):
        last = 1 if i == len(pieces) - 1 else 0
        out.append(struct.pack("<I", len(piece) << 3 | last)[:3])
        out.append(piece)
    return b"".join(out)


def tar(members):
    """A tar of `members` (name, bytes; None for a directory, a str for a
    symbolic link to it), owned by root, the same bytes each time."""
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.USTAR_FORMAT) as t:
        for name, data in members:
            info = tarfile.TarInfo(name)
            info.mtime, info.uname, info.gname = TIME, "root", "root"
            if data is None:
                info.type, info.mode = tarfile.DIRTYPE, 0o755
                t.addfile(info)
            elif isinstance(data, str):
                info.type, info.linkname, info.mode = tarfile.SYMTYPE, data, 0o777
                t.addfile(info)
            else:
                info.size = len(data)
                info.mode = 0o755 if "/bin/" in name else 0o644
                t.addfile(info, io.BytesIO(data))
    return raw.getvalue()


def compress(data, how):
    """`data` as makepkg compresses a package: zst, xz or gz."""
    if how == "zst":
        return zst(data)
    if how == "xz":
        return lzma.compress(data, format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC64)
    return gzip.compress(data, 6, mtime=0)


def pkginfo(name, version, arch, fields=()):
    """A .PKGINFO as makepkg writes it, its fields in order, then
    `fields` (key, value)."""
    lines = ["# Generated by makepkg 6.1.0", "# using fakeroot version 1.36",
             f"pkgname = {name}", f"pkgbase = {name}", "xdata = pkgtype=pkg",
             f"pkgver = {version}", f"pkgdesc = {name}, a small package for the replay corpus",
             f"url = https://example.invalid/{name}", f"builddate = {TIME}",
             "packager = Replay Tester <replay@example.invalid>", "size = 4096",
             f"arch = {arch}", "license = MIT"]
    lines += [f"{k} = {v}" for k, v in fields]
    return ("\n".join(lines) + "\n").encode()


def program(name, version, salt=""):
    return f"#!/bin/sh\necho {name} {version}{salt}\n".encode()


def package(name, version, arch="x86_64", how="zst", fields=(), info=None, members=None,
            salt=""):
    """A package as makepkg makes it: .BUILDINFO, .PKGINFO (or `info`),
    .MTREE, then its files (or `members`); `salt`, other bytes of the
    same package."""
    if info is None:
        info = pkginfo(name, version, arch, fields)
    if members is None:
        members = [(".BUILDINFO", b"format = 2\npkgname = %s\n" % name.encode()),
                   (".PKGINFO", info), (".MTREE", gzip.compress(b"#mtree\n", 9, mtime=0)),
                   ("usr/", None), ("usr/bin/", None),
                   (f"usr/bin/{name}", program(name, version, salt)),
                   ("usr/share/", None), (f"usr/share/{name}/", None),
                   (f"usr/share/{name}/README", f"{name} {version}\n".encode())]
    return compress(tar(members), how)


def file_name(name, version, arch="x86_64", how="zst"):
    return f"{name}-{version}-{arch}.pkg.tar.{how}"


