def reads(c, who):
    add, seq = c.add, c.seq
    for repo in REPOS:
        b = f"/{repo}"
        d = f"{b}/{repo}/x86_64"
        for rel in tree(repo):
            add(f"arch {repo}{rel} {who}", who, "GET", b + rel)
        for rel in heads(repo):
            add(f"arch {repo} HEAD {rel} {who}", who, "HEAD", b + rel)
        # A listing of the files sorted by size, in a sequence (the
        # fuzz takes no mutant of one).
        seq(f"arch {repo} listing by size {who}", who, [
            ("GET", f"{d}/?sort=size", {}, None),
            ("GET", f"{d}/?sort=size&order=desc", {}, None),
            ("GET", f"{d}/?sort=time&order=desc", {}, None)])
        # A package's validators (it has no time: an ETag alone) and
        # ranges; of its signature and of the databases too. The ETags
        # are the public repository's, which every identity reads (the
        # private one's packages are the same: the seed made both
        # alike; its databases are not, they name their repository).
        pkg = f"{d}/{F10}"
        pe = "{arch archpub/archpub/x86_64/%s %s.etag}" % (F10, who)
        mine = etag(HELLO_10)
        for name, h in (("inm", {"If-None-Match": pe}), ("inm any", {"If-None-Match": "*"}),
                        ("inm other", {"If-None-Match": '"other"'}),
                        ("inm weak", {"If-None-Match": "W/" + mine}),
                        ("inm list", {"If-None-Match": f'"x", {mine}'}),
                        ("ims future", {"If-Modified-Since": FUTURE}),
                        ("ims past", {"If-Modified-Since": PAST}),
                        ("inm other and ims", {"If-None-Match": '"other"',
                                               "If-Modified-Since": FUTURE}),
                        ("range", {"Range": "bytes=0-9"}),
                        ("range from 10", {"Range": "bytes=10-"}),
                        ("range last 5", {"Range": "bytes=-5"}),
                        ("range past the end", {"Range": "bytes=999999-"}),
                        ("ranges", {"Range": "bytes=0-1,4-5"}),
                        ("range bad", {"Range": "bytes=a-b"}),
                        ("if-range", {"Range": "bytes=0-9", "If-Range": pe}),
                        ("if-range stale", {"Range": "bytes=0-9", "If-Range": '"stale"'}),
                        ("if-range date", {"Range": "bytes=0-9", "If-Range": FUTURE})):
            add(f"arch {repo} package {name} {who}", who, "GET", pkg, h)
        add(f"arch {repo} package HEAD inm {who}", who, "HEAD", pkg, {"If-None-Match": pe})
        add(f"arch {repo} signature range {who}", who, "GET", pkg + ".sig",
            {"Range": "bytes=0-2"})
        # A database's, by its ETag (a label's is another's).
        db = f"/{repo}/x86_64/{repo}.db"
        de = "{arch %s%s %s.etag}" % (repo, db, who)
        for name, rel, h in (("inm", db, {"If-None-Match": de}),
                             ("ims future", db, {"If-Modified-Since": FUTURE}),
                             ("range", db, {"Range": "bytes=0-9"}),
                             ("range last 5", db, {"Range": "bytes=-5"}),
                             ("range past the end", db, {"Range": "bytes=999999-"}),
                             ("if-range", db, {"Range": "bytes=0-9", "If-Range": de}),
                             ("accept", db, {"Accept": "text/html"}),
                             ("inm", "/@first" + db, {"If-None-Match": de}),
                             ("inm", f"/{repo}/x86_64/{repo}.db.tar.gz", {"If-None-Match": de}),
                             ("inm", f"/{repo}/x86_64/", {"If-None-Match": "*"}),
                             ("range", f"/{repo}/x86_64/", {"Range": "bytes=0-9"})):
            add(f"arch {repo} {name} {rel} {who}", who, "GET", b + rel, h)
        add(f"arch {repo} HEAD inm {db} {who}", who, "HEAD", b + db, {"If-None-Match": de})
    for rel in NOSIGN_TREE:
        add(f"arch archnosign{rel} {who}", who, "GET", f"/archnosign{rel}")
    add(f"arch archnosign HEAD {who}", who, "HEAD", "/archnosign/archnosign/x86_64/archnosign.db")
    # A repository with nothing in it yet: no version at all.
    for rel in EMPTY:
        add(f"arch archempty{rel} {who}", who, "GET", f"/archempty{rel}")
    add(f"arch archempty HEAD {who}", who, "HEAD", "/archempty/")
    # What the server refuses before the repository is asked: a method
    # it takes from none.
    for m in ("OPTIONS", "PATCH"):
        add(f"arch {m} {who}", who, m, "/archpub/archpub/x86_64/archpub.db")


class Zeros:
    """`n` zero bytes, sent a MiB at a time (http.client sends an
    iterable as it comes, with the Content-Length given): a body past a
    limit, not held whole (its length keeps the fuzz's mutants off it)."""

    def __init__(self, n):
        self.n = n

    def __len__(self):
        return self.n

    def __iter__(self):
        piece = bytes(1 << 20)
        left = self.n
        while left > 0:
            yield piece if left >= len(piece) else piece[:left]
            left -= len(piece)


def chunked(pieces):
    """A body of HTTP/1.1 chunks, one for each of `pieces`, then the last
    (sent as it is: http.client chunks nothing itself where the request
    says Transfer-Encoding)."""
    return b"".join(b"%x\r\n" % len(p) + p + b"\r\n" for p in pieces) + b"0\r\n\r\n"


# A name of 64 hex digits, as rpm's repodata files are named: a package
# of that name for an architecture named repodata, in a pacman
# repository named so too, is named by its content to the server.
HEX = hashlib.sha256(b"replay").hexdigest()
HEXREPO = f"{HEX}-r"


def mine(who):
    """What `who` puts in each signed repository, if it may (repo
    "pub", "priv" or both; pacman repository, None for the one of the
    repository's name; architecture; file name): one package replaced,
    one in extra, one put to the address it is served at; and in the
    public one, the packages its uploads take though they might not,
    and those whose paths the server's rules name."""
    out = [("both", None, "x86_64", file_name(f"w-{who}", "1.0-1")),
           ("both", "extra", "x86_64", file_name(f"w-{who}", "1.1-1", how="xz")),
           ("both", None, "x86_64", file_name(f"w-{who}", "1.2-1", how="gz"))]
    for v, how in (("1.0-1", "zst"), ("1.1-1", "xz"), ("1.2-1", "gz"), ("1:1.3-1", "zst")):
        out.append(("pub", None, "x86_64", file_name(f"t-{who}", v, how=how)))
    out += [("pub", None, "i686", file_name(f"i-{who}", "1.0-1", "i686")),
            ("pub", "by-hash", "x86_64", file_name(f"b-{who}", "1.0-1", "any")),
            ("pub", "by-hash", "aarch64", file_name(f"b-{who}", "1.0-1", "any")),
            ("pub", HEXREPO, "repodata", file_name(f"{HEX}-{who}", "1.0-1", "repodata")),
            ("pub", HEXREPO, "repodata", file_name(f"{HEX}-SUMS-{who}", "1.0-1", "repodata"))]
    return out


