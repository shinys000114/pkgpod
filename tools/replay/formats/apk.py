def tar(entries, end=True):
    """A tar (ustar; pax where an entry has records) of `entries` (name,
    bytes, mode, type, pax records or None), each at BUILT, owned by
    root; `end`: with its end blocks (a control part has none, so that
    the data's tar reads as its continuation, as abuild makes it)."""
    out = bytearray()
    for name, data, mode, kind, pax in entries:
        ti = tarfile.TarInfo(name)
        ti.size, ti.mode, ti.type, ti.mtime = len(data), mode, kind, BUILT
        ti.uid = ti.gid = 0
        ti.uname = ti.gname = "root"
        if pax:
            ti.pax_headers = dict(pax)
        fmt = tarfile.PAX_FORMAT if pax else tarfile.USTAR_FORMAT
        out += ti.tobuf(fmt, "utf-8", "surrogateescape")
        out += data + b"\0" * (-len(data) % 512)
    if end:
        out += b"\0" * 1024
    return bytes(out)


def gz(data):
    return gzip.compress(data, compresslevel=9, mtime=0)


def data_part(files):
    """The data part of `files` (path, bytes, mode): its directories, then
    each file with the SHA-1 apk checks in a pax record, as abuild-tar
    writes them."""
    dirs = sorted({"/".join(p.split("/")[:i]) + "/" for p, _, _ in files
                   for i in range(1, p.count("/") + 1)})
    entries = [(d, b"", 0o755, tarfile.DIRTYPE, None) for d in dirs]
    entries += [(p, d, m, tarfile.REGTYPE,
                 {"APK-TOOLS.checksum.SHA1": hashlib.sha1(d, usedforsecurity=False).hexdigest()})
                for p, d, m in files]
    return gz(tar(entries))


def package(name, version, arch, *, files=None, desc=None, fields=(), info=None,
            scripts=(), signed=False, datahash=True, data=None):
    """An apk (v2) of `name` `version` for `arch`, the same bytes each
    time: an optional signature part, the control part (.PKGINFO, then
    `scripts` (name, bytes)), the data part (`files`, path, bytes, mode;
    a script if None). .PKGINFO says what abuild's does, then `fields`
    (key, value, repeated keys kept; or a line as it is), then the
    data's hash unless `datahash` is false (or another hex given);
    `info`, the whole text in its place; `data`, other bytes in the
    data part's place."""
    if files is None:
        files = [(f"usr/bin/{name}", f"#!/bin/sh\necho {name} {version}\n".encode(), 0o755)]
    part = data_part(files) if data is None else data
    if info is None:
        lines = ["# Generated by the replay's abuild", f"pkgname = {name}",
                 f"pkgver = {version}", f"pkgdesc = {desc or name + ', a package of the replay'}",
                 f"url = https://example.invalid/{name}", f"builddate = {BUILT}",
                 "packager = Replay <replay@example.invalid>",
                 f"size = {sum(len(d) for _, d, _ in files)}", f"arch = {arch}",
                 f"origin = {name}", "license = MIT"]
        lines += [f if isinstance(f, str) else f"{f[0]} = {f[1]}" for f in fields]
        if datahash:
            h = datahash if isinstance(datahash, str) else hashlib.sha256(part).hexdigest()
            lines.append(f"datahash = {h}")
        # A string's lone surrogates (\udcXX) are the bytes they escape.
        info = ("\n".join(lines) + "\n").encode("utf-8", "surrogateescape")
    control = gz(tar([(".PKGINFO", info, 0o644, tarfile.REGTYPE, None)]
                     + [(n, d, 0o755, tarfile.REGTYPE, None) for n, d in scripts], end=False))
    sig = b""
    if signed:
        # Not a real signature: the server reads past it, apk would not.
        sig = gz(tar([(".SIGN.RSA.replay.rsa.pub", b"not a real signature\n", 0o644,
                       tarfile.REGTYPE, None)], end=False))
    return sig + control + part


def file_name(name, version):
    return f"{name}-{version}.apk"


