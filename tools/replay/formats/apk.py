# What the seed does to each of the public and private repositories,
# in order, as (how, place or label, packages): uploads by the CLI
# (several at once), PUTs to the tree as curl -T does (to the upload
# address, to a file's address in the place, to the repository's own,
# one with replace); labels of the version so far.
SEED = [
    ("cli", "v3.22/main", [HELLO_10]),
    ("label", "first", None),
    ("/upload?branch=v3.22&repository=main", None, HELLO_11),
    ("/v3.22/main/x86_64/" + file_name("motd", "2-r0") + "?branch=v3.22&repository=main", None,
     MOTD),
    ("cli", "v3.22/community", [TOOL, BLINK]),
    ("/?branch=v3.22&repository=community", None, MOTD),
    ("label", "second", None),
    ("/" + file_name("hello", "1.0-r0") + "?branch=v3.20&repository=main", None, HELLO_10),
    ("/upload?branch=v3.22&repository=main&replace=true", None, HELLO_11B),
]


def seed(p, fx):
    # Alpine: hosted public and private (see SEED), one whose settings
    # name its architectures and description, one with nothing in it.
    aa = auth_header("admin")

    def put(path, body):
        st, _, out = request("PUT", path, aa, body)
        if st != 201:
            raise SystemExit(f"apk upload {path}: {st} {out[:200]}")

    def cli_upload(repo, place, bodies):
        paths = []
        for body in bodies:
            f = os.path.join(fx, f"apk-{hashlib.sha256(body).hexdigest()[:16]}.apk")
            with open(f, "wb") as fh:
                fh.write(body)
            paths.append(f)
        branch, repository = place.split("/")
        p.cli("upload", repo, *paths, "-s", f"branch={branch}", "-s", f"repository={repository}")

    for repo, public in (("apkpub", "true"), ("apkpriv", "false")):
        p.cli("repo", "create", repo, "-f", "apk", "-s", f"public={public}")
        for how, at, body in SEED:
            if how == "label":
                p.cli("label", repo, at)
            elif how == "cli":
                cli_upload(repo, at, body)
            else:
                put(f"/{repo}{how}", body)
    p.cli("repo", "create", "apkriscv", "-f", "apk", "-s", "public=true", "-s",
          "architectures=x86_64,riscv64", "-s", "description=Replay's Alpine packages")
    cli_upload("apkriscv", "v3.22/main", [HELLO_10, MOTD, TOOL])
    p.cli("repo", "create", "apkempty", "-f", "apk", "-s", "public=true")
    # The key's name (the server's, made with the first index), for the
    # reads.
    st, _, body = request("GET", "/apkempty/", aa)
    names = sorted(set(re.findall(rb'href="(pkgpod-[0-9a-f]{8}\.rsa\.pub)"', body)))
    if st != 200 or len(names) != 1:
        raise SystemExit(f"apk: no key in the listing of apkempty ({st})")
    with open(os.path.join(fx, KEYS), "w") as f:
        json.dump({"key": names[0].decode()}, f)


